const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const app=fs.readFileSync("src/fizgig/web/static/app.js","utf8");
const start=app.indexOf("const STUDIO_AI_FOCUS=");
const end=app.indexOf("function captionAiControlsMount(",start);
assert(start>=0&&end>start);
const context={S:{cap:{studioAi:{}}},qwenOn:()=>true,capTagger:()=>null,capDesc:()=>({kind:"sentences"}),qwenTask:()=>({key:"training",instruction:"Write a caption."}),capType:()=>null,$:()=>({checked:true,value:""}),capExtrasText:()=>""};
vm.runInNewContext(app.slice(start,end),context);
assert.equal(context.studioAiPreset("object_exhaustive").focus,"object");
assert.equal(context.studioAiPreset("object_exhaustive").detail,"full");
assert.equal(context.studioAiPreset("training").detail,"balanced");
let job=context.studioAiJobOptions();
assert.equal(job.output_format,"natural");
assert.equal(job.instruction,"Write a caption.");
context.S.cap.studioAi.format="tags";
context.S.cap.studioAi.write="append";
job=context.studioAiJobOptions();
assert.equal(job.append,true);
assert.equal(job.overwrite,false);
assert.match(job.instruction,/comma-separated/);
context.S.cap.studioAi.user["tags:training"]="Custom tag prompt";
assert.equal(context.studioAiJobOptions().instruction,"Custom tag prompt");
context.S.cap.studioAi.format="natural";
assert.equal(context.studioAiJobOptions().instruction,"Write a caption.");
console.log("Auto-Captioner presets and append routing passed");
