"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const Tags=require("../src/fizgig/web/static/caption_studio_tags.js");
const app=fs.readFileSync("src/fizgig/web/static/app.js","utf8");
const css=fs.readFileSync("src/fizgig/web/static/style.css","utf8");
const from=app.indexOf("  const waterfallQuery=");
const to=app.indexOf("  const mapReturn=",from);
const query=new Function("CaptionStudioTags",app.slice(from,to)+"return waterfallQuery;")(Tags);
const state={tag:"lion",peer:"blue eyes",branchTrail:["feline","lion"]};
const predicate=Tags.compileSearch(query(state));
assert.equal(predicate(["feline","lion","blue eyes"]),true);
assert.equal(predicate(["lion","blue eyes"]),false);
assert.equal(Tags.compileSearch(query(state,null))(["feline","lion"]),true);
assert.ok(app.includes("directWaterfall:true"));
assert.ok(app.includes('S.cap.studioExploreMode="waterfall"'));
assert.ok(app.includes("network.resumeMap("));
const head=app.slice(app.indexOf("const header=el(\"header\",{class:\"studio-waterfall-filter"),app.indexOf("fullStage.append(header);",app.indexOf("const header=el(\"header\",{class:\"studio-waterfall-filter")));
assert.ok(head.includes("studio-waterfall-tag-heading"));
assert.ok(head.includes("Filter by related tag"));
assert.ok(head.includes("Back to map"));
assert.ok(!head.includes("createTagFilterBar"));
assert.ok(app.includes('if(view==="waterfall"&&commitTagFilter())'));
assert.ok(css.includes('.studio-tb-explore.is-filtered-waterfall > .studio-tb-waterfall'));
console.log("Shared Waterfall collection header, cumulative tag filtering, and real view navigation checks passed");
